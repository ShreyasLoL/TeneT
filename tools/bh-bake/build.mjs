function compileTarget(srcName, exeName) {
  const srcPath = path.join(__dirname, srcName);
  const outPath = path.join(BIN_DIR, exeName);
  const res = spawnSync(
    'clang++',
    ['-O3', '-std=c++20', '-DNDEBUG', '-Wall', '-Wextra', srcPath, '-o', outPath],
    { cwd: __dirname, stdio: 'inherit' },
  );
  if (res.status !== 0) {
    throw new Error(`clang++ failed compiling ${srcName} (exit ${res.status})`);
  }
  console.log(`Built ${outPath}`);
}

